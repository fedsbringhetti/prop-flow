-- =============================================================================
-- Audit log: append-only, partizionato per mese, con redazione dei campi sensibili.
-- Nessuna FK verso users/organizations: la traccia deve sopravvivere alle cancellazioni.
-- =============================================================================

CREATE TABLE app.audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    occurred_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    org_id          UUID,
    actor_user_id   UUID,
    actor_role      TEXT,
    action          app.audit_action NOT NULL,
    table_name      TEXT NOT NULL,
    record_id       UUID,
    changed_fields  TEXT[],
    old_data        JSONB,
    new_data        JSONB,
    request_id      TEXT,
    client_ip       INET,
    user_agent      TEXT,
    -- session_user (non current_user): dentro una funzione SECURITY DEFINER
    -- current_user sarebbe il definer, non il ruolo realmente connesso.
    db_user         TEXT NOT NULL DEFAULT session_user,
    PRIMARY KEY (id, occurred_at)   -- la PK di una tabella partizionata include la chiave
) PARTITION BY RANGE (occurred_at);

-- Partizione di sicurezza: nessun INSERT può mai fallire per partizione mancante
CREATE TABLE app.audit_log_default PARTITION OF app.audit_log DEFAULT;

CREATE INDEX audit_log_record_ix  ON app.audit_log (table_name, record_id, occurred_at DESC);
CREATE INDEX audit_log_org_ix     ON app.audit_log (org_id, occurred_at DESC);
CREATE INDEX audit_log_actor_ix   ON app.audit_log (actor_user_id, occurred_at DESC);
CREATE INDEX audit_log_request_ix ON app.audit_log (request_id) WHERE request_id IS NOT NULL;

-- Manutenzione partizioni: invocata da un cron job mensile (o pg_partman).
-- Revoca i privilegi di scrittura sulla nuova partizione: la traccia la scrive
-- solo il trigger SECURITY DEFINER, mai il ruolo applicativo.
CREATE FUNCTION app.ensure_audit_partition(p_month DATE) RETURNS text
  LANGUAGE plpgsql AS $$
DECLARE
  v_start DATE := date_trunc('month', p_month)::date;
  v_end   DATE := (date_trunc('month', p_month) + INTERVAL '1 month')::date;
  v_name  TEXT := format('audit_log_%s', to_char(v_start, 'YYYY_MM'));
  v_role  TEXT;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'app' AND c.relname = v_name
  ) THEN
    EXECUTE format(
      'CREATE TABLE app.%I PARTITION OF app.audit_log FOR VALUES FROM (%L) TO (%L)',
      v_name, v_start, v_end);
  END IF;

  FOREACH v_role IN ARRAY ARRAY['propflow_app', 'propflow_worker'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = v_role) THEN
      EXECUTE format('GRANT SELECT ON app.%I TO %I', v_name, v_role);
      EXECUTE format('REVOKE INSERT, UPDATE, DELETE ON app.%I FROM %I', v_name, v_role);
    END IF;
  END LOOP;

  RETURN v_name;
END $$;

-- Partizioni iniziali: mese corrente + successivo
SELECT app.ensure_audit_partition(CURRENT_DATE);
SELECT app.ensure_audit_partition((CURRENT_DATE + INTERVAL '1 month')::date);

-- Append-only anche per il ruolo owner: nessun UPDATE/DELETE possibile
CREATE TRIGGER audit_log_no_update BEFORE UPDATE ON app.audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION app.tg_forbid_mutation();
CREATE TRIGGER audit_log_no_delete BEFORE DELETE ON app.audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION app.tg_forbid_mutation();

-- ---------------------------------------------------------------------------
-- Trigger di audit generico.
-- SECURITY DEFINER: scrive nell'audit anche se il ruolo applicativo non ha INSERT
-- su audit_log (l'app non può falsificare né sopprimere la traccia).
-- TG_ARGV[0] (opzionale) = array di colonne da redigere.
-- ---------------------------------------------------------------------------
CREATE FUNCTION app.tg_audit() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = app, pg_temp AS $$
DECLARE
  v_old     jsonb;
  v_new     jsonb;
  v_changed text[];
  v_redact  text[] := CASE WHEN TG_NARGS > 0 THEN TG_ARGV[0]::text[] ELSE '{}'::text[] END;
  v_action  app.audit_action;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_action := 'insert';  v_new := to_jsonb(NEW);
  ELSIF TG_OP = 'UPDATE' THEN
    v_action := 'update';  v_old := to_jsonb(OLD);  v_new := to_jsonb(NEW);
  ELSE
    v_action := 'delete';  v_old := to_jsonb(OLD);
  END IF;

  IF TG_OP = 'UPDATE' THEN
    SELECT array_agg(e.k ORDER BY e.k) INTO v_changed
      FROM jsonb_each(v_new) AS e(k, v)
     WHERE v_old -> e.k IS DISTINCT FROM e.v;

    -- update a vuoto (es. re-save senza modifiche): niente rumore nell'audit
    IF v_changed IS NULL THEN
      RETURN NULL;
    END IF;
  END IF;

  -- Redazione PRIMA della scrittura: segreti e PII non entrano mai nell'audit trail
  IF array_length(v_redact, 1) IS NOT NULL THEN
    v_old := app.jsonb_redact(v_old, v_redact);
    v_new := app.jsonb_redact(v_new, v_redact);
  END IF;

  INSERT INTO app.audit_log (
      org_id, actor_user_id, actor_role, action, table_name, record_id,
      changed_fields, old_data, new_data, request_id, client_ip, user_agent, db_user)
  VALUES (
      COALESCE((v_new ->> 'org_id')::uuid, (v_old ->> 'org_id')::uuid, app.current_org_id()),
      app.current_user_id(),
      NULLIF(current_setting('app.actor_role', true), ''),
      v_action,
      TG_TABLE_NAME,
      COALESCE((v_new ->> 'id')::uuid, (v_old ->> 'id')::uuid),
      v_changed, v_old, v_new,
      app.request_id(), app.client_ip(), app.user_agent(), session_user);

  RETURN NULL;   -- AFTER trigger
END $$;

COMMENT ON FUNCTION app.tg_audit IS
  'Audit a livello DB (defense-in-depth): traccia anche le modifiche fatte da script
   o console, non solo quelle passate dal Service Layer. Le colonne elencate in
   TG_ARGV[0] vengono sostituite con "[REDACTED]" (requisito: niente dati sensibili nei log).';
