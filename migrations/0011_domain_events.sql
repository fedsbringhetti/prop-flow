-- =============================================================================
-- Outbox transazionale: "Event Bus solo predisposto"
-- Scritta dal Service Layer nella stessa transazione del comando (nessun trigger:
-- l'evento di dominio è una decisione del dominio, non un effetto collaterale del DB).
-- =============================================================================

CREATE TABLE app.domain_events (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    -- ordinamento totale stabile per il dispatcher (l'UUID v7 ordina, ma non basta)
    sequence        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    org_id          UUID REFERENCES app.organizations (id) ON DELETE SET NULL,

    aggregate_type  TEXT NOT NULL,                -- 'Lease', 'Ticket', 'Payment'…
    aggregate_id    UUID NOT NULL,
    event_type      TEXT NOT NULL,                -- 'lease.activated', 'ticket.triaged'…
    event_version   SMALLINT NOT NULL DEFAULT 1,
    payload         JSONB NOT NULL,
    -- correlation_id / causation_id / actor_id / trace_id per il tracing distribuito
    metadata        JSONB NOT NULL DEFAULT '{}'::jsonb,

    status          app.event_status NOT NULL DEFAULT 'pending',
    occurred_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    available_at    TIMESTAMPTZ NOT NULL DEFAULT now(),   -- backoff dei retry
    published_at    TIMESTAMPTZ,
    attempts        SMALLINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX domain_events_sequence_uk ON app.domain_events (sequence);
-- coda del dispatcher: indice parziale minuscolo anche con milioni di eventi dispatchati
CREATE INDEX domain_events_pending_ix ON app.domain_events (available_at, sequence)
    WHERE status = ANY (ARRAY['pending','failed']::app.event_status[]);
CREATE INDEX domain_events_aggregate_ix ON app.domain_events
    (aggregate_type, aggregate_id, sequence);
CREATE INDEX domain_events_type_ix ON app.domain_events (event_type, occurred_at DESC);
CREATE INDEX domain_events_org_ix ON app.domain_events (org_id, occurred_at DESC);

COMMENT ON TABLE app.domain_events IS
  'Outbox. Il dispatcher (propflow_worker, BYPASSRLS) legge con FOR UPDATE SKIP LOCKED
   e pubblica sul broker. Sostituire il broker non richiede modifiche allo schema.';
